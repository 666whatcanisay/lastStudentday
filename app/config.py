# ---------- 向量路过滤：绝对下限 + 相对带宽 ----------
#
# ⚠️ 实测发现（重要，不要改回单一绝对阈值）：
#    bge-small-zh 的相似度是**长度相关**的 —— 短查询的分数系统性偏低：
#      「打车」          top1 = 0.3441
#      「从哪到哪」       top1 = 0.3787
#      「打车花了多少钱」   top1 = 0.4331
#      「谁开的发票」      top1 = 0.5433
#      「INV-...-001…」  top1 = 0.6398
#    曾经用单一阈值 0.45，结果把「打车」「从哪到哪」这类短口语查询的
#    向量路**整条掐断**（0.3441 远低于 0.45），而长查询却全通过。
#    绝对阈值无法同时适配长短查询，这是结构性缺陷，不是参数没调好。
#
#    另一个观察：无论查询长短，**top1 与 top2 的落差都很小**
#    （「谁开的发票」0.5433 vs 0.5320，仅差 0.011），真正明显的落差出现在
#    top2 之后。所以正确的做法是「跟着 top1 走」，而不是「卡一个死线」。
#
# ⚠️⚠️ 更关键的实测结论：**向量路无法区分相关与无关**
#    在同一批语料上，无关查询的向量分甚至比相关查询更高：
#      打车（相关）        0.3441
#      从哪到哪（相关）     0.3787
#      股票行情分析（无关）  0.4005   ← 比"打车"还高
#      今天天气怎么样（无关） 0.3707
#      量子纠缠退相干（无关） 0.3710
#    根因：语料是同质的（5 篇全是票据/订单），任何查询与任何文档都有
#    中等相似度，分数分布高度重叠。这是稠密检索在小而同质语料上的固有局限，
#    不是参数没调好 —— 换任何阈值都分不开。
#
#    所以本项目的架构是：
#      · 关键词路（BM25）承担**相关性判定** —— 它对无关查询真的返回 0 分，
#        是有真实判别力的那一路
#      · 向量路只承担**召回扩展** —— 负责把"语义相近但用词不同"的捞回来，
#        不负责说"没有"
#      · 生成层用防幻觉 Prompt 兜底（"资料不足必须回答无法回答"）
#
# 三级参数：
#   RETRIEVE_MIN_SCORE     —— 向量噪声下限。只挡掉 0.2x 一档的明显垃圾，
#                             不承担区分相关/无关的职责。
#   RETRIEVE_SCORE_MARGIN  —— 向量相对带宽。保留 score >= top1 - margin，
#                             让过滤强度自适应查询长度。
#   RETRIEVE_NO_HIT_SCORE  —— 无结果判定的向量置信度兜底。见下方说明。
RETRIEVE_MIN_SCORE = 0.30
RETRIEVE_SCORE_MARGIN = 0.10

# 判定「检索不到相关内容」时，向量路需要的置信度下限。
#
# 规则：**关键词路覆盖率低 且 向量路 top1 低于本值** → 判定为无结果。
#       （仅 vec 模式时退化为只看向量）
#
# 为什么用"且"：单看向量会把"股票行情分析"(0.4005) 判成有结果；
#              单看关键词会把纯语义查询（无字面重叠）判成无结果。
#              两者都弱才敢说"没有"。
#
# ── 阶段五重标（语料 4 篇 → 25 篇，评估集 22 → 34 条）────────────────
# 用 scripts/calibrate_gate.py 做二维扫描后，从 0.45 上调到 0.55。
#   负样本 vec_top1 上界 0.5051（「量子芯片的良率数据」）
#   正样本 vec_top1 下界 0.5085（「打车报销的凭证」）
#   → **向量维可用窗口只有 (0.5051, 0.5085)，宽 0.0034**，窄到不可用。
#   旧值 0.45 拦不住任何 vec_top1 > 0.45 的负样本（4 条负样本里 2 条超线）。
#   取 0.55 而不是窗口中点：窗口只有 0.0034 宽，卡中点是在拟合噪声；
#   0.55 位于正样本 vec_top1 中位数（0.594）以下，是"不激进"的取值。
#
# ⚠️ 0.55 已越过正样本下界 0.5085，有 8 条正样本在**向量维**被判为低置信
#    （#4/#6/#7/#13/#14/#17/#30/#33）。它们没被误杀，**完全依赖覆盖率维度**
#    （这几条 coverage 在 0.12~0.62，远高于覆盖率下限）。
#    → 覆盖率是主判据，本值只是冗余兜底。
#    → **两阈值耦合**：若将来放宽 RETRIEVE_BM25_COVERAGE_MIN，必须同时把本值
#      降回 ≤0.50，否则那 8 条立刻变成误杀。改一个必须看另一个。
#
# ⚠️ 本值是**语料相关**的经验值：它成立的前提是本语料上"口语化查询都能
#    通过同义扩展被 BM25 覆盖"。语料换成非票据类（用词与口语差异大）后
#    必须重跑 scripts/calibrate_gate.py 重测。
RETRIEVE_NO_HIT_SCORE = 0.55

# 判定「检索不到相关内容」时，关键词路的**覆盖率**下限。
#
# 覆盖率 = bm25_top1 / Σ IDF(查询的每个词)，见 bm25_index.coverage()
# 含义：最好的那个文档满足了这条查询多少比例的"信息需求"。
#
# ── 为什么要把原来的「bm25 零命中」换掉 ──────────────────────────────
# 原规则要求关键词路**一条都不命中**才算"没有"。这是个二元条件，
# 只要查询里含任何一个常见词（公司/金额/日期/发票），BM25 就必然有命中，
# 门控直接被关掉，向量路判得再准也白搭。
#
# 实测（真实 LLM 联调）：负样本「公司员工的社保缴纳基数是多少？」
#   vec_top1 = 0.3958（远低于 0.45，本该被拦）
#   bm25 命中 2 条，top1 = 0.800（弱命中）→ 门控失效 → 返回 4 条无关片段
#
# ── 为什么用覆盖率而不是原始分 ────────────────────────────────────────
# 原始 BM25 分是**语料相关**的（idf 依赖语料规模 N），换语料就失效。
# 覆盖率是比值，天然可迁移。
#
# ── 阈值怎么定的（阶段五重标：语料 4 篇 → 25 篇，评估集 22 → 34 条）──
# 实测分离情况（scripts/calibrate_gate.py，模式 hybrid+rw，走生产链路）：
#   负样本覆盖率上界 0.0931（「年度绩效考核评分标准」）
#   正样本覆盖率下界 0.1206（「金额五万五千元的订单」）
#   → 间隔 0.0275，**相对宽度约 30%，单维干净分离**
# 取几何中点 sqrt(0.0931*0.1206) ≈ 0.1060，按"宁低勿高"往**下**圆整到 0.100。
# 两侧余量：负样本侧 +7.4%（越界就漏拦），正样本侧 +20.6%（越界就误杀）。
#
# ── 历史值（保留痕迹，不要删）────────────────────────────────────────
# 旧值 0.045 是在 **4 篇语料 / 22 条查询**上标的（当时记录：负 ≤0.026 / 正 ≥0.082）。
# 语料扩到 25 篇后实测分离区间整体上移，0.045 已落进负样本区间内部
# → 门控基本失效 → 4 条负样本只拦住 1 条（正确率 25%）。
# 重标到 0.100 后：负样本正确率 100%（4/4），正样本零误杀，
# 有效 Recall@1 96.7% / Recall@5 100.0% / MRR 0.9778（与重标前一致，正样本无损失）。
#
# ⚠️ 风险不对称，取值宁低勿高：
#    阈值偏高 → 合法查询被判"无结果"，用户什么都拿不到（**严重**）
#    阈值偏低 → 多返回几条勉强相关的片段，LLM 通常还能自行拒答（**轻微**）
#    所以若将来要调，往**低**调比往高调安全。
#
# ⚠️ 仅 4 条负样本支撑，语料再扩充后必须重跑 scripts/calibrate_gate.py 重验。
RETRIEVE_BM25_COVERAGE_MIN = 0.100

# ---------- 分数融合 ----------
FUSION_MODE = "rrf"          # rrf（默认，鲁棒） / weighted（加权归一化，便于对比调优）
RRF_K = 60                   # RRF 平滑常数

# 两路权重（rrf 与 weighted 模式共用）
#
# ⚠️ 实测依据（scripts/measure_rewrite.py，5 篇真实语料 / 8 条查询）：
#   bm25_weight=1.0 → 融合 Top-1 命中 6/8
